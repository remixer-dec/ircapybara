package server

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/rsa"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"time"
)

const selfSignedOrg = "IRCapybara self-signed"

// tlsConfig intentionally supports legacy IRC clients. TLS 1.0 is the oldest
// protocol version supported by Go's crypto/tls package. The explicit RSA
// cipher suites are needed by older clients that do not support ECDHE.
// TLS 1.3 suites are controlled by Go and are unaffected by CipherSuites.
func tlsConfig(certFile, keyFile, serverName string, autoGenerate bool) (*tls.Config, error) {
	cert, err := tls.LoadX509KeyPair(certFile, keyFile)
	if err != nil && autoGenerate && (errors.Is(err, os.ErrNotExist) || isPathMissing(certFile) || isPathMissing(keyFile)) {
		if err := generateSelfSigned(certFile, keyFile, serverName); err != nil {
			return nil, err
		}
		cert, err = tls.LoadX509KeyPair(certFile, keyFile)
	}
	if err != nil {
		return nil, err
	}

	// v0.1/v0.2 generated Ed25519 certificates. Some older IRC TLS stacks do
	// not advertise any signature scheme compatible with Ed25519. Migrate only
	// certificates that we can positively identify as IRCapybara-generated;
	// never overwrite an administrator-provided certificate.
	if autoGenerate && isLegacyAutoGeneratedEd25519(&cert) {
		if err := generateSelfSigned(certFile, keyFile, serverName); err != nil {
			return nil, fmt.Errorf("migrate autogenerated TLS certificate: %w", err)
		}
		cert, err = tls.LoadX509KeyPair(certFile, keyFile)
		if err != nil {
			return nil, err
		}
	}

	return &tls.Config{
		Certificates: []tls.Certificate{cert},
		MinVersion:   tls.VersionTLS10,
		CipherSuites: []uint16{
			// Preferred suites for TLS 1.0-1.2 clients.
			tls.TLS_ECDHE_RSA_WITH_AES_128_GCM_SHA256,
			tls.TLS_ECDHE_RSA_WITH_AES_256_GCM_SHA384,
			tls.TLS_ECDHE_RSA_WITH_CHACHA20_POLY1305_SHA256,
			tls.TLS_ECDHE_RSA_WITH_AES_128_CBC_SHA,
			tls.TLS_ECDHE_RSA_WITH_AES_256_CBC_SHA,
			// Compatibility fallback for clients without ECDHE support.
			tls.TLS_RSA_WITH_AES_128_GCM_SHA256,
			tls.TLS_RSA_WITH_AES_256_GCM_SHA384,
			tls.TLS_RSA_WITH_AES_128_CBC_SHA,
			tls.TLS_RSA_WITH_AES_256_CBC_SHA,
		},
	}, nil
}

func isLegacyAutoGeneratedEd25519(cert *tls.Certificate) bool {
	if cert == nil || len(cert.Certificate) == 0 {
		return false
	}
	leaf := cert.Leaf
	if leaf == nil {
		parsed, err := x509.ParseCertificate(cert.Certificate[0])
		if err != nil {
			return false
		}
		leaf = parsed
	}
	if _, ok := leaf.PublicKey.(ed25519.PublicKey); !ok {
		return false
	}
	for _, org := range leaf.Subject.Organization {
		if org == selfSignedOrg {
			return true
		}
	}
	return false
}

func isPathMissing(path string) bool {
	_, err := os.Stat(path)
	return errors.Is(err, os.ErrNotExist)
}

func generateSelfSigned(certFile, keyFile, serverName string) error {
	if err := os.MkdirAll(filepath.Dir(certFile), 0o700); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(keyFile), 0o700); err != nil {
		return err
	}

	// RSA is deliberately used instead of Ed25519 for broad IRC-client TLS
	// compatibility. 2048-bit RSA is sufficient for this self-signed endpoint
	// certificate and is supported by substantially older TLS implementations.
	priv, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		return err
	}
	serialLimit := new(big.Int).Lsh(big.NewInt(1), 128)
	serial, err := rand.Int(rand.Reader, serialLimit)
	if err != nil {
		return err
	}
	now := time.Now()
	tmpl := x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: serverName, Organization: []string{selfSignedOrg}},
		NotBefore:             now.Add(-5 * time.Minute),
		NotAfter:              now.AddDate(5, 0, 0),
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
	}
	if ip := net.ParseIP(serverName); ip != nil {
		tmpl.IPAddresses = []net.IP{ip}
	} else {
		tmpl.DNSNames = []string{serverName}
	}
	der, err := x509.CreateCertificate(rand.Reader, &tmpl, &tmpl, &priv.PublicKey, priv)
	if err != nil {
		return err
	}

	if err := os.WriteFile(certFile, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o600); err != nil {
		return err
	}
	return os.WriteFile(keyFile, pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: x509.MarshalPKCS1PrivateKey(priv)}), 0o600)
}
