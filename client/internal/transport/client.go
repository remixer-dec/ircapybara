package transport

import (
	"bufio"
	"context"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"encoding/pem"
	"errors"
	"fmt"
	"io"
	"net"
	"strings"
	"sync"
	"time"
)

const (
	MaxLineBytes = 132 * 1024
	EventBuffer  = 256
)

type Config struct {
	Address              string
	ServerName           string
	Timeout              time.Duration
	AllowInsecureTLS     bool
	PinnedCertificatePEM []byte
}

type EventType string

const (
	EventConnected    EventType = "connected"
	EventLine         EventType = "line"
	EventDisconnected EventType = "disconnected"
	EventError        EventType = "error"
)

type Event struct {
	Type EventType
	Line string
	Err  error
}

type Client struct {
	mu        sync.Mutex
	conn      net.Conn
	writer    *bufio.Writer
	events    chan Event
	done      chan struct{}
	closeOnce sync.Once
}

type tlsPins struct {
	certificates map[[32]byte]struct{}
	publicKeys   map[[32]byte]struct{}
}

func New() *Client {
	return &Client{events: make(chan Event, EventBuffer), done: make(chan struct{})}
}

func (c *Client) Events() <-chan Event { return c.events }

// Done is closed once the client has been closed or its connection ended.
// Events that were still queued at that point may never be delivered.
func (c *Client) Done() <-chan struct{} { return c.done }

func (c *Client) Connect(ctx context.Context, cfg Config) error {
	if cfg.Timeout <= 0 {
		cfg.Timeout = 12 * time.Second
	}
	host, _, err := net.SplitHostPort(cfg.Address)
	if err != nil {
		return fmt.Errorf("invalid server address: %w", err)
	}
	serverName := strings.TrimSpace(cfg.ServerName)
	if serverName == "" {
		serverName = host
	}

	tlsConfig := &tls.Config{
		MinVersion: tls.VersionTLS12,
		ServerName: serverName,
	}
	if len(cfg.PinnedCertificatePEM) > 0 {
		pins, err := parseTLSPins(cfg.PinnedCertificatePEM)
		if err != nil {
			return fmt.Errorf("invalid pinned TLS certificate/public key: %w", err)
		}
		// Pinning intentionally bypasses the normal X.509 chain/hostname path so
		// locally generated certificates that modern x509 rejects can still be
		// trusted explicitly. The peer must present the exact pinned certificate
		// or the exact pinned public key.
		tlsConfig.InsecureSkipVerify = true // verification is performed below
		tlsConfig.VerifyPeerCertificate = func(rawCerts [][]byte, _ [][]*x509.Certificate) error {
			return verifyPinnedPeer(rawCerts, pins)
		}
	} else if cfg.AllowInsecureTLS {
		// Explicit user preference for local/self-signed servers. Encryption still
		// occurs, but certificate identity is not authenticated.
		tlsConfig.InsecureSkipVerify = true
	}

	dialer := &net.Dialer{Timeout: cfg.Timeout, KeepAlive: 30 * time.Second}
	raw, err := dialer.DialContext(ctx, "tcp", cfg.Address)
	if err != nil {
		return err
	}

	tlsConn := tls.Client(raw, tlsConfig)
	deadline := time.Now().Add(cfg.Timeout)
	_ = tlsConn.SetDeadline(deadline)
	if err := tlsConn.HandshakeContext(ctx); err != nil {
		_ = raw.Close()
		return fmt.Errorf("TLS handshake failed: %w", err)
	}
	_ = tlsConn.SetDeadline(time.Time{})

	c.mu.Lock()
	if c.conn != nil {
		c.mu.Unlock()
		_ = tlsConn.Close()
		return errors.New("already connected")
	}
	c.conn = tlsConn
	c.writer = bufio.NewWriterSize(tlsConn, 16*1024)
	c.mu.Unlock()

	c.emit(Event{Type: EventConnected})
	go c.readLoop(tlsConn)
	return nil
}

func parseTLSPins(data []byte) (tlsPins, error) {
	pins := tlsPins{
		certificates: make(map[[32]byte]struct{}),
		publicKeys:   make(map[[32]byte]struct{}),
	}
	remaining := data
	parsed := 0
	for {
		block, rest := pem.Decode(remaining)
		if block == nil {
			break
		}
		remaining = rest
		switch block.Type {
		case "CERTIFICATE":
			// Exact certificate pinning does not require the certificate to pass
			// Go's X.509 standards checks. This is important for explicitly trusted
			// local certificates generated by older/private tooling.
			pins.certificates[sha256.Sum256(block.Bytes)] = struct{}{}
			if cert, err := x509.ParseCertificate(block.Bytes); err == nil {
				pins.publicKeys[sha256.Sum256(cert.RawSubjectPublicKeyInfo)] = struct{}{}
			}
			parsed++
		case "PUBLIC KEY":
			key, err := x509.ParsePKIXPublicKey(block.Bytes)
			if err != nil {
				return tlsPins{}, err
			}
			der, err := x509.MarshalPKIXPublicKey(key)
			if err != nil {
				return tlsPins{}, err
			}
			pins.publicKeys[sha256.Sum256(der)] = struct{}{}
			parsed++
		}
	}
	if parsed == 0 {
		// Also accept a raw DER certificate. Exact byte pinning remains useful
		// even when x509.ParseCertificate rejects a non-standard certificate.
		if len(data) == 0 {
			return tlsPins{}, errors.New("empty certificate/public-key file")
		}
		pins.certificates[sha256.Sum256(data)] = struct{}{}
		if cert, err := x509.ParseCertificate(data); err == nil {
			pins.publicKeys[sha256.Sum256(cert.RawSubjectPublicKeyInfo)] = struct{}{}
		}
	}
	return pins, nil
}

func verifyPinnedPeer(rawCerts [][]byte, pins tlsPins) error {
	if len(rawCerts) == 0 {
		return errors.New("server presented no certificate")
	}
	leafRaw := rawCerts[0]
	if _, ok := pins.certificates[sha256.Sum256(leafRaw)]; ok {
		return nil
	}
	leaf, err := x509.ParseCertificate(leafRaw)
	if err != nil {
		return fmt.Errorf("cannot parse server certificate: %w", err)
	}
	if _, ok := pins.publicKeys[sha256.Sum256(leaf.RawSubjectPublicKeyInfo)]; ok {
		return nil
	}
	return errors.New("server certificate does not match the pinned certificate or public key")
}

func (c *Client) Send(line string) error {
	return c.SendLines([]string{line})
}

// SendLines keeps client-initiated batches contiguous on the wire.
func (c *Client) SendLines(lines []string) error {
	for _, line := range lines {
		if strings.ContainsAny(line, "\r\n") {
			return errors.New("raw line contains newline")
		}
		if len(line)+2 > MaxLineBytes {
			return fmt.Errorf("IRC line exceeds %d bytes", MaxLineBytes)
		}
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.conn == nil || c.writer == nil {
		return errors.New("not connected")
	}
	_ = c.conn.SetWriteDeadline(time.Now().Add(10 * time.Second))
	defer c.conn.SetWriteDeadline(time.Time{})
	for _, line := range lines {
		if _, err := c.writer.WriteString(line + "\r\n"); err != nil {
			_ = c.conn.Close()
			return err
		}
	}
	if err := c.writer.Flush(); err != nil {
		_ = c.conn.Close()
		return err
	}
	return nil
}

func (c *Client) Close() error {
	c.mu.Lock()
	conn := c.conn
	c.conn = nil
	c.writer = nil
	c.mu.Unlock()
	var err error
	if conn != nil {
		err = conn.Close()
	}
	c.stop()
	return err
}

func (c *Client) stop() {
	c.closeOnce.Do(func() { close(c.done) })
}

func (c *Client) readLoop(conn net.Conn) {
	r := bufio.NewReaderSize(conn, 32*1024)
	for {
		line, err := readLineBounded(r, MaxLineBytes)
		if len(line) > 0 {
			c.emit(Event{Type: EventLine, Line: line})
		}
		if err != nil {
			if !errors.Is(err, io.EOF) && !errors.Is(err, net.ErrClosed) {
				c.emit(Event{Type: EventError, Err: err})
			}
			c.mu.Lock()
			if c.conn == conn {
				c.conn = nil
				c.writer = nil
			}
			c.mu.Unlock()
			c.emit(Event{Type: EventDisconnected, Err: err})
			c.stop()
			return
		}
	}
}

func readLineBounded(r *bufio.Reader, max int) (string, error) {
	var buf []byte
	for {
		frag, err := r.ReadSlice('\n')
		if len(buf)+len(frag) > max {
			return "", fmt.Errorf("IRC line exceeds %d bytes", max)
		}
		buf = append(buf, frag...)
		if err == nil {
			return strings.TrimSuffix(strings.TrimSuffix(string(buf), "\n"), "\r"), nil
		}
		if errors.Is(err, bufio.ErrBufferFull) {
			continue
		}
		if len(buf) > 0 && errors.Is(err, io.EOF) {
			return strings.TrimSuffix(strings.TrimSuffix(string(buf), "\n"), "\r"), io.EOF
		}
		return "", err
	}
}

func (c *Client) emit(ev Event) bool {
	// IRC is an ordered byte stream. Dropping an event here corrupts higher-level
	// semantics (most visibly attachment chunk numbering). Keep the queue bounded
	// by applying backpressure to the socket reader instead of discarding lines.
	select {
	case c.events <- ev:
		return true
	case <-c.done:
		return false
	}
}
